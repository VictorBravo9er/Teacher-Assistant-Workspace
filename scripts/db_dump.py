#!/usr/bin/env python3
"""
Teach&Learn Database Dump Tool (Supabase CLI)

- Schemas: Generates separate local SQL files for each schema (schema.public.sql,
  schema.ai.sql, schema.langgraph.sql in supabase/schemas/).
- Data: Dumps table records for all specified schemas directly into supabase/seed.sql
  (overwriting existing seed fixtures).
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import threading
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
from typing import TextIO

# Add scripts directory to sys.path to allow importing _env_helper
sys.path.insert(0, str(Path(__file__).resolve().parent))
import _env_helper  # pyright: ignore[reportImplicitRelativeImport]

DEFAULT_SCHEMAS: str = "public,ai,langgraph"
DEFAULT_SCHEMA_DIR: str = "supabase/schemas"
DEFAULT_DATA_FILE: str = "supabase/seed.sql"

_dump_print_lock = threading.Lock()


def _safe_dump_print(*args: object, file: TextIO | None = None) -> None:
    with _dump_print_lock:
        print(*args, file=file)


def _prepend_banner(file_path: Path, mode: str, schemas: str) -> None:
    """Prepends a standard autogenerated banner to dumped SQL files."""
    try:
        content = file_path.read_text(encoding="utf-8")
        kind_label = (
            "Table Data Fixtures" if mode == "data" else f"DDL Schema ({schemas})"
        )
        cmd_hint = "make db-dump-data" if mode == "data" else "make db-dump-schema"
        banner = (
            "-- -------------------------------------------------------------\n"
            "-- AUTO-GENERATED FILE — DO NOT EDIT MANUALLY\n"
            f"-- Generated by: scripts/db_dump.py (`{cmd_hint}`)\n"
            f"-- Content: {kind_label}\n"
            "-- -------------------------------------------------------------\n\n"
        )
        if not content.startswith(
            "-- -------------------------------------------------------------"
        ):
            _ = file_path.write_text(banner + content.lstrip("\n"), encoding="utf-8")
    except Exception as e:
        _safe_dump_print(
            f"   ⚠️ Could not prepend banner to {file_path.name}: {e}",
            file=sys.stderr,
        )


class _DBDumpArgs(argparse.Namespace):
    schema_only: bool = False
    data_only: bool = False
    both: bool = False
    schema: str = DEFAULT_SCHEMAS
    dir: Path | None = None
    file: Path | None = None
    db_url: str = _env_helper.POSTGRES_URI
    local: bool = False
    linked: bool = False
    use_copy: bool = False
    keep_comments: bool = False
    dry_run: bool = False
    parallel: bool = True


def _run_supabase_dump(
    mode: str,
    output_file: Path,
    schemas: str = DEFAULT_SCHEMAS,
    db_url: str | None = None,
    local: bool = False,
    linked: bool = False,
    use_copy: bool = False,
    keep_comments: bool = False,
    dry_run: bool = False,
    quiet: bool = False,
) -> int:
    """Internal helper to execute `supabase db dump`."""
    root_dir = Path(__file__).resolve().parent.parent

    cmd: list[str] = ["npx", "-y", "--quiet", "supabase", "db", "dump"]

    if local:
        cmd.append("--local")
    elif linked:
        cmd.append("--linked")
    elif db_url:
        cmd.extend(["--db-url", db_url])
    else:
        _safe_dump_print(
            "❌ Error: No database target specified. Missing POSTGRES_URI or --local/--linked flag.",
            file=sys.stderr,
        )
        return 1

    cmd.extend(["--schema", schemas])

    if mode == "data":
        cmd.append("--data-only")
        if use_copy:
            cmd.append("--use-copy")

    if keep_comments:
        cmd.append("--keep-comments")

    if dry_run:
        cmd.append("--dry-run")
    else:
        output_file.parent.mkdir(parents=True, exist_ok=True)
        cmd.extend(["-f", str(output_file)])

    kind_label = "table data" if mode == "data" else "DDL schema"
    target_label = (
        "local container"
        if local
        else ("linked project" if linked else "configured database")
    )
    if not quiet:
        _safe_dump_print(
            f"\n▶️  Generating local SQL file for [{schemas}] ({kind_label}) from {target_label}..."
        )
        if not dry_run:
            try:
                rel_path = output_file.relative_to(root_dir)
            except ValueError:
                rel_path = output_file
            _safe_dump_print(f"   Destination: {rel_path}")

    if quiet:
        result = subprocess.run(cmd, cwd=str(root_dir), capture_output=True, text=True)
    else:
        result = subprocess.run(cmd, cwd=str(root_dir))

    if result.returncode != 0:
        _safe_dump_print(
            f"   ❌ Error generating {kind_label} for [{schemas}] via Supabase CLI (exit {result.returncode}).",
            file=sys.stderr,
        )
        if quiet and result.stderr:
            _safe_dump_print(f"      {result.stderr.strip()}", file=sys.stderr)
        return result.returncode

    if not dry_run and output_file.exists():
        _prepend_banner(output_file, mode, schemas)

    if not dry_run and not quiet:
        _safe_dump_print(
            f"   ✅ Successfully generated local SQL file: {output_file.name}"
        )
    return 0


def dump_schemas(
    db_url: str | None = None,
    output_dir: Path | None = None,
    schemas: str = DEFAULT_SCHEMAS,
    file_override: Path | None = None,
    local: bool = False,
    linked: bool = False,
    keep_comments: bool = False,
    dry_run: bool = False,
    quiet: bool = False,
    parallel: bool = True,
) -> int:
    """Generates separate local DDL schema SQL files for each specified schema."""
    root_dir = Path(__file__).resolve().parent.parent
    target_dir = (
        output_dir if output_dir is not None else (root_dir / DEFAULT_SCHEMA_DIR)
    )
    schema_list = [s.strip() for s in schemas.split(",") if s.strip()]

    def _resolve_target_file(s: str) -> Path:
        if file_override is not None:
            if "{schema}" in str(file_override):
                return Path(str(file_override).format(schema=s))
            elif len(schema_list) == 1:
                return file_override
            else:
                return (
                    file_override.parent
                    / f"{file_override.stem}_{s}{file_override.suffix}"
                )
        return target_dir / f"schema.{s}.sql"

    def _execute_dump(s: str) -> tuple[str, int, Path]:
        target_file = _resolve_target_file(s)
        rc = _run_supabase_dump(
            mode="schema",
            output_file=target_file,
            schemas=s,
            db_url=db_url if db_url is not None else _env_helper.POSTGRES_URI,
            local=local,
            linked=linked,
            keep_comments=keep_comments,
            dry_run=dry_run,
            quiet=quiet,
        )
        return s, rc, target_file

    results_by_schema: dict[str, tuple[int, Path]] = {}

    if parallel and len(schema_list) > 1:
        with ThreadPoolExecutor(max_workers=len(schema_list)) as executor:
            futures = [executor.submit(_execute_dump, s) for s in schema_list]
            for future in futures:
                s, rc, target_file = future.result()
                results_by_schema[s] = (rc, target_file)
    else:
        for s in schema_list:
            s, rc, target_file = _execute_dump(s)
            results_by_schema[s] = (rc, target_file)
            if rc != 0:
                break

    # Check for any failures
    for s in schema_list:
        if s in results_by_schema:
            rc, _target_file = results_by_schema[s]
            if rc != 0:
                return rc

    # Render deterministic progress tree if quiet and not dry_run
    if quiet and not dry_run:
        for idx, s in enumerate(schema_list):
            if s in results_by_schema:
                _rc, target_file = results_by_schema[s]
                is_last = idx == len(schema_list) - 1
                branch = "└──" if is_last else "├──"
                size_kb = (
                    target_file.stat().st_size / 1024
                    if target_file.exists()
                    else 0.0
                )
                _safe_dump_print(
                    f"   {branch} {target_file.name:<26} ({size_kb:.1f} KB)"
                )

    return 0


def dump_data(
    db_url: str | None = None,
    output_file: Path | None = None,
    schemas: str = DEFAULT_SCHEMAS,
    local: bool = False,
    linked: bool = False,
    use_copy: bool = False,
    keep_comments: bool = False,
    dry_run: bool = False,
    quiet: bool = False,
) -> int:
    """Dumps table data for the specified schemas directly into seed.sql (overwrites)."""
    root_dir = Path(__file__).resolve().parent.parent
    target_file = (
        output_file if output_file is not None else (root_dir / DEFAULT_DATA_FILE)
    )

    rc = _run_supabase_dump(
        mode="data",
        output_file=target_file,
        schemas=schemas,
        db_url=db_url if db_url is not None else _env_helper.POSTGRES_URI,
        local=local,
        linked=linked,
        use_copy=use_copy,
        keep_comments=keep_comments,
        dry_run=dry_run,
        quiet=quiet,
    )
    if rc != 0:
        return rc

    if quiet and not dry_run:
        size_kb = target_file.stat().st_size / 1024 if target_file.exists() else 0.0
        _safe_dump_print(
            f"   └── {target_file.name:<26} ({size_kb:.1f} KB, schemas: {schemas})"
        )

    return 0


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Teach&Learn Database Dump Tool (Supabase CLI)",
    )
    group = parser.add_mutually_exclusive_group()
    _ = group.add_argument(
        "--schema-only",
        action="store_true",
        help="Dump separate DDL schema files (default).",
    )
    _ = group.add_argument(
        "--data-only",
        action="store_true",
        help="Dump table data into seed.sql.",
    )
    _ = group.add_argument(
        "--both",
        action="store_true",
        help="Dump both separate DDL schemas and data into seed.sql.",
    )
    _ = parser.add_argument(
        "-s",
        "--schema",
        default=DEFAULT_SCHEMAS,
        help=f"Comma-separated list of schemas to dump (default: '{DEFAULT_SCHEMAS}').",
    )
    _ = parser.add_argument(
        "-d",
        "--dir",
        type=Path,
        default=None,
        help="Destination directory for schema SQL files. Defaults to supabase/schemas.",
    )
    _ = parser.add_argument(
        "-f",
        "--file",
        type=Path,
        default=None,
        help="Destination file path for data dump (defaults to supabase/seed.sql).",
    )
    _ = parser.add_argument(
        "--db-url",
        default=_env_helper.POSTGRES_URI,
        help="Direct Postgres connection URL. Defaults to POSTGRES_URI from environment.",
    )
    _ = parser.add_argument(
        "--local",
        action="store_true",
        help="Dump from local running Supabase container instead of remote URL.",
    )
    _ = parser.add_argument(
        "--linked",
        action="store_true",
        help="Dump from linked Supabase project.",
    )
    _ = parser.add_argument(
        "--use-copy",
        action="store_true",
        help="Use COPY statements instead of INSERT statements for data dump.",
    )
    _ = parser.add_argument(
        "--keep-comments",
        action="store_true",
        help="Keep commented lines in the dumped output.",
    )
    _ = parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print the pg_dump command that would be executed without writing files.",
    )
    _ = parser.add_argument(
        "--no-parallel",
        dest="parallel",
        action="store_false",
        help="Dump schemas sequentially instead of in parallel.",
    )

    args = parser.parse_args(namespace=_DBDumpArgs())

    print("=" * 60)
    print("📦 Teach&Learn Database Dump Tool (Supabase CLI)")
    print("=" * 60)

    if args.both:
        rc = dump_schemas(
            db_url=args.db_url,
            output_dir=args.dir,
            schemas=args.schema,
            file_override=args.file,
            local=args.local,
            linked=args.linked,
            keep_comments=args.keep_comments,
            dry_run=args.dry_run,
            parallel=args.parallel,
        )
        if rc != 0:
            sys.exit(rc)

        rc = dump_data(
            db_url=args.db_url,
            output_file=args.file,
            schemas=args.schema,
            local=args.local,
            linked=args.linked,
            use_copy=args.use_copy,
            keep_comments=args.keep_comments,
            dry_run=args.dry_run,
        )
        if rc != 0:
            sys.exit(rc)
    else:
        if args.data_only:
            rc = dump_data(
                db_url=args.db_url,
                output_file=args.file,
                schemas=args.schema,
                local=args.local,
                linked=args.linked,
                use_copy=args.use_copy,
                keep_comments=args.keep_comments,
                dry_run=args.dry_run,
            )
        else:
            rc = dump_schemas(
                db_url=args.db_url,
                output_dir=args.dir,
                schemas=args.schema,
                file_override=args.file,
                local=args.local,
                linked=args.linked,
                keep_comments=args.keep_comments,
                dry_run=args.dry_run,
                parallel=args.parallel,
            )

        if rc != 0:
            sys.exit(rc)

    print("\n" + "=" * 60)
    print("🎉 Dump Operation Complete!")
    print("=" * 60)


if __name__ == "__main__":
    main()
